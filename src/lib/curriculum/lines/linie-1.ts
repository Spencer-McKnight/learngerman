/** A noun taught as one unit with its article. */
export function noun(
  lemma: string,
  gender: Gender,
  english: string,
  rank: number,
  plural?: string,
  forms: string[] = [],
  tags?: string[],
): Lexeme {
  return {
    id: `${lemma}:N`,
    lemma,
    pos: "N",
    gender,
    ...(plural ? { plural } : {}),
    english,
    rank,
    cefr: "A1",
    forms,
    ...(tags ? { tags } : {}),
  };
}

/** Any other part of speech. */
export function word(
  lemma: string,
  pos: Exclude<Pos, "N">,
  english: string,
  rank: number,
  forms: string[] = [],
  tags?: string[],
): Lexeme {
  return { id: `${lemma}:${pos}`, lemma, pos, english, rank, cefr: "A1", forms, ...(tags ? { tags } : {}) };
}

