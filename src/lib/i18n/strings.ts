/**
 * All interface chrome — headings, action words, hints, feedback —
 * abstracted into one typed dictionary per language. German content
 * being *learned* (stories, words, dialogue lines) never lives here;
 * this is only the frame around it, so a beginner can switch the
 * frame to English while the German stays German.
 *
 * `de` defines the shape; `en` is checked against it, so a key added
 * to one language cannot silently go missing in the other.
 */

export type UiLang = "de" | "en";

export const UI_LANG_COOKIE = "ui-lang";

export function parseUiLang(value: unknown): UiLang {
  return value === "en" ? "en" : "de";
}

